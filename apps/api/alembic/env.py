"""Alembic runtime environment for the Atlas API.

Two things make this file more than the generated template:

1. **The URL comes from the environment**, never from ``alembic.ini``. ``ATLAS_DATABASE_URL``
   is the single source, shared with the running app, so a migration can never be applied to
   a different database than the one the service talks to.

2. **Model metadata is imported from every module** so ``--autogenerate`` sees the whole
   schema. An import missed here does not fail loudly: autogenerate simply emits
   ``DROP TABLE`` for the tables it cannot see. The registry below is therefore explicit,
   and ``_import_module_models`` raises if a declared module is missing.
"""

from __future__ import annotations

import asyncio
import importlib
import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import Connection, pool
from sqlalchemy.ext.asyncio import async_engine_from_config

from atlas_core.db import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name, disable_existing_loggers=False)

#: Modules whose ORM models participate in the schema. Adding a module means adding it here;
#: the alternative (walking the package tree) silently tolerates a typo in a package name.
MODEL_MODULES = (
    "atlas_api.modules.auth.repository.tables",
    "atlas_api.modules.credentials.repository.tables",
)


def _import_module_models() -> None:
    """Import every module's table definitions so they register on ``Base.metadata``.

    A module that has no tables yet is allowed to be absent — the branches are created
    before the tables they will hold. Anything else propagates: an ImportError inside a
    tables module (a bad column type, a circular import) must stop the migration, not
    degrade autogenerate into producing destructive SQL.
    """
    for dotted in MODEL_MODULES:
        try:
            importlib.import_module(dotted)
        except ModuleNotFoundError as exc:
            if exc.name != dotted:
                raise
            continue


_import_module_models()
target_metadata = Base.metadata


def _database_url() -> str:
    url = os.getenv("ATLAS_DATABASE_URL") or config.get_main_option("sqlalchemy.url")
    if not url:
        raise SystemExit(
            "FATAL: ATLAS_DATABASE_URL is not set — refusing to guess a database to migrate"
        )
    if url.startswith("postgresql://"):
        url = url.replace("postgresql://", "postgresql+asyncpg://", 1)
    elif url.startswith("postgres://"):
        url = url.replace("postgres://", "postgresql+asyncpg://", 1)
    return url


def _configure(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        # Render server-side defaults into autogenerated migrations. Without this a column
        # with server_default=now() appears identical to one without, and the difference
        # only surfaces as a NOT NULL violation from a non-Python writer.
        compare_server_default=True,
        compare_type=True,
        # Long-lived tables get ALTERed for years; a named constraint is one whose drop
        # statement can be written by hand during an incident.
        render_as_batch=False,
        include_schemas=False,
        transaction_per_migration=True,
    )


def run_migrations_offline() -> None:
    """Emit SQL to stdout instead of executing it (``alembic upgrade heads --sql``).

    This is the reviewable artifact for a production change: the DBA reads the SQL, not the
    Python that generates it.
    """
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def _run_sync(connection: Connection) -> None:
    _configure(connection)
    with context.begin_transaction():
        context.run_migrations()


async def _run_async() -> None:
    section = config.get_section(config.config_ini_section, {})
    section["sqlalchemy.url"] = _database_url()
    # NullPool: a migration run is one connection for one process lifetime. A pool here just
    # leaves sockets open long enough for the CI job to be blamed for "too many connections".
    engine = async_engine_from_config(section, prefix="sqlalchemy.", poolclass=pool.NullPool)
    try:
        async with engine.connect() as connection:
            await connection.run_sync(_run_sync)
    finally:
        await engine.dispose()


def run_migrations_online() -> None:
    asyncio.run(_run_async())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
